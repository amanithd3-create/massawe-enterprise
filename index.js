import "dotenv/config";
import express from "express";
import cors from "cors";
import helmet from "helmet";
import rateLimit from "express-rate-limit";
import {prisma} from "./db.js";
import authRoutes from "./routes/auth.js";
import productRoutes from "./routes/products.js";
import orderRoutes from "./routes/orders.js";
import adminRoutes from "./routes/admin.js";
import paymentRoutes from "./routes/payments.js";
const app=express();
app.use(helmet());
app.use(cors({origin:process.env.CLIENT_ORIGIN?.split(",")||"http://localhost:5173"}));
app.use(express.json({limit:"1mb"}));
app.use("/api",rateLimit({windowMs:15*60*1000,limit:300,standardHeaders:true,legacyHeaders:false}));
app.get("/api/health",(req,res)=>res.json({ok:true,service:"Massawe Enteprice API"}));
app.use("/api/auth",authRoutes);
app.use("/api/products",productRoutes);
app.use("/api/orders",orderRoutes);
app.use("/api/admin",adminRoutes);
app.use("/api/payments",paymentRoutes);
app.use((err,req,res,next)=>{console.error(err);res.status(500).json({error:"An unexpected server error occurred."});});
const port=process.env.PORT||4000;
app.listen(port,()=>console.log(`Massawe API listening on ${port}`));
process.on("SIGTERM",async()=>{await prisma.$disconnect();process.exit(0);});
